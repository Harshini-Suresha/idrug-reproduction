"""Generate SYNTHETIC datasets in the same CSV format as data/ (ids are prefixed DRUG_/DIS_/TGT_).
They match the *sizes* of the paper's datasets, not the real biology. Usage: python gen_datasets.py"""
import os, numpy as np, pandas as pd

SPECS = {  # name: (drugs_dd, diseases, drugs_dt, targets, shared_drugs, links_dd, links_dt, K mechanisms)
    "synthetic_small":       (250,  200,  250,  150, 200,    2400,   2300, 15),
    "synthetic_gold_scale":  (593,  313,  593, 1011, 593,    1933,   3427, 30),   # Gottlieb-style sizes
    "synthetic_paper_scale": (1321, 3966, 946, 3610, 469,  111481,  10234, 80),   # CTD + DrugBank sizes (Table 1)
}

def memb(rng, n, K, per=2):
    M = np.zeros((n, K), dtype=np.float32)
    for i in range(n): M[i, rng.choice(K, rng.integers(1, per + 1), replace=False)] = 1
    return M

def links(rng, Ma, Mb, target):
    """~95% of links follow shared mechanisms, ~5% are random background noise."""
    shared = (Ma @ Mb.T > 0); N = shared.size; s = shared.mean()
    bg = 0.05 * target / N
    p = np.clip(0.95 * target / (s * N), 0.01, 0.9)
    return rng.random(shared.shape) < np.where(shared, p, bg)

def sim(rng, M, noise=0.35):
    Mn = M / np.linalg.norm(M, axis=1, keepdims=True)
    S = Mn @ Mn.T + rng.normal(0, noise, (len(M),) * 2).astype(np.float32)
    S = np.clip((S + S.T) / 2, 0, 1); S[S < 0.1] = 0; np.fill_diagonal(S, 1.0)
    return np.round(S, 3)

def write_square(S, ids, path):
    pd.DataFrame(S, index=ids, columns=ids).to_csv(path, float_format="%g")

def build(name, spec, seed=0):
    n1, nd, n2, nt, ns, ldd, ldt, K = spec
    rng = np.random.default_rng(seed); out = os.path.join("data_synthetic", name); os.makedirs(out, exist_ok=True)
    total = n1 + n2 - ns
    drug_ids = [f"DRUG_{i:05d}" for i in range(total)]
    dis_ids = [f"DIS_{i:05d}" for i in range(nd)]; tgt_ids = [f"TGT_{i:05d}" for i in range(nt)]
    Md, Mi, Mt = memb(rng, total, K), memb(rng, nd, K), memb(rng, nt, K)
    d1 = np.arange(0, n1); d2 = np.arange(n1 - ns, total)
    for X, rows, cols, fn, hdr, tgt in (
            (links(rng, Md[d1], Mi, ldd), d1, dis_ids, "drug_disease.csv", ("drug_id", "disease_id"), ldd),
            (links(rng, Md[d2], Mt, ldt), d2, tgt_ids, "drug_target.csv", ("drug_id", "target_id"), ldt)):
        r, c = np.nonzero(X)
        pd.DataFrame({hdr[0]: [drug_ids[rows[i]] for i in r], hdr[1]: [cols[j] for j in c]}).to_csv(os.path.join(out, fn), index=False)
    write_square(sim(rng, Md), drug_ids, os.path.join(out, "drug_similarity.csv.gz"))
    write_square(sim(rng, Mi), dis_ids, os.path.join(out, "disease_similarity.csv.gz"))
    write_square(sim(rng, Mt), tgt_ids, os.path.join(out, "target_similarity.csv.gz"))
    open(os.path.join(out, "SYNTHETIC.txt"), "w").write(
        f"SYNTHETIC data, generated by gen_datasets.py (seed {seed}). Sizes mimic the paper; the links are NOT real biology.\n"
        f"drug-disease: {n1} drugs x {nd} diseases, ~{ldd} links | drug-target: {n2} drugs x {nt} targets, ~{ldt} links | shared drugs: {ns}\n")
    print(name, "written")

if __name__ == "__main__":
    for k, v in SPECS.items(): build(k, v)
